/**
 * @file Custom hook for judge prompt generation
 * @description Handles API generation logic and state management
 */

import { useCallback, useRef, useState } from "react";

import { useDevLogger } from "@/lib/dev-logger";

import { validateJudgePrompt } from "./validation";

interface UseJudgePromptGenerationProps {
  challengePrompt: string;
  loading?: boolean;
  onPromptChange?: ((prompt: string) => void) | undefined;
}

export function useJudgePromptGeneration({
  challengePrompt,
  loading = false,
  onPromptChange,
}: UseJudgePromptGenerationProps) {
  const logUI = useDevLogger("JudgePromptEditor");

  const [isGenerating, setIsGenerating] = useState(false);
  const [apiError, setApiError] = useState<string | null>(null);
  const [hasGenerated, setHasGenerated] = useState(false);

  // Track if prompt was auto-generated to avoid infinite loops
  const autoGeneratedRef = useRef(false);

  const handleGeneratePrompt = useCallback(
    async (setJudgePrompt: (prompt: string) => void) => {
      if (!challengePrompt.trim() || isGenerating || loading) {
        return;
      }

      setIsGenerating(true);
      setApiError(null);
      autoGeneratedRef.current = true;

      logUI("generate_start", { challengePrompt: challengePrompt.substring(0, 100) });

      try {
        const { typedApi } = await import("@/lib/api-client");
        const data = await typedApi(
          "POST /api/judge-prompt",
          {},
          {
            challengePrompt: challengePrompt.trim(),
          },
        );

        if (!data.success) {
          throw new Error(data.error || "Failed to generate judge prompt");
        }

        setJudgePrompt(data.judgePrompt);
        setHasGenerated(true);

        // Notify parent if callback provided
        if (onPromptChange && validateJudgePrompt(data.judgePrompt).isValid) {
          onPromptChange(data.judgePrompt.trim());
        }

        logUI("generate_success", {
          length: data.judgePrompt.length,
          isValid: validateJudgePrompt(data.judgePrompt).isValid,
        });
      } catch (error) {
        const message = error instanceof Error ? error.message : "Failed to generate judge prompt";
        setApiError(message);
        logUI("generate_error", { error: message });
      } finally {
        setIsGenerating(false);
        autoGeneratedRef.current = false;
      }
    },
    [challengePrompt, isGenerating, loading, logUI, onPromptChange],
  );

  const clearApiError = useCallback(() => {
    setApiError(null);
  }, []);

  const canGenerate = challengePrompt.trim().length > 0 && !loading && !isGenerating;

  return {
    isGenerating,
    apiError,
    hasGenerated,
    canGenerate,
    handleGeneratePrompt,
    clearApiError,
  };
}
